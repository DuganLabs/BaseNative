import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

// Generates docs/package-inventory.md from packages/*/package.json plus a live
// registry lookup. Never hand-edit the output — an inventory that drifts from the
// registry is worse than none (PRD W3 constraint, applied here too).
//
//   node scripts/package-inventory.js          write docs/package-inventory.md
//   node scripts/package-inventory.js --check  exit 1 if the committed copy is stale

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'docs', 'package-inventory.md');

/** Canonical registry for the @basenative scope, read from .npmrc. */
function scopeRegistry() {
  const npmrc = readFileSync(join(ROOT, '.npmrc'), 'utf8');
  const m = npmrc.match(/^@basenative:registry\s*=\s*(\S+)/m);
  return m ? m[1].replace(/\/$/, '') : 'https://registry.npmjs.org';
}

/** Latest published version on npmjs, or null. Public mirror only — GH Packages needs auth. */
async function npmjsVersion(name) {
  const res = await fetch(`https://registry.npmjs.org/${encodeURIComponent(name)}`);
  if (!res.ok) return null;
  const body = await res.json();
  return body['dist-tags']?.latest ?? null;
}

function readPackages() {
  const dir = join(ROOT, 'packages');
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => {
      const raw = readFileSync(join(dir, e.name, 'package.json'), 'utf8');
      return { dir: e.name, ...JSON.parse(raw) };
    })
    .filter((p) => p.name)
    .sort((a, b) => a.name.localeCompare(b.name));
}

function render(pkgs, registry) {
  const publishable = pkgs.filter((p) => !p.private);
  const priv = pkgs.filter((p) => p.private);
  const behind = publishable.filter((p) => p.npmjs && p.npmjs !== p.version);
  const absent = publishable.filter((p) => !p.npmjs);
  const redundant = publishable.filter(
    (p) => p.publishConfig?.registry?.replace(/\/$/, '') === registry,
  );

  const rows = pkgs
    .map((p) => {
      const state = p.private
        ? 'private'
        : !p.npmjs
          ? 'never on npmjs'
          : p.npmjs === p.version
            ? 'in sync'
            : `behind (${p.npmjs})`;
      return `| \`${p.name}\` | ${p.version} | ${p.npmjs ?? '—'} | ${state} |`;
    })
    .join('\n');

  return `# Package inventory

<!-- GENERATED by scripts/package-inventory.js — do not edit. Run \`node scripts/package-inventory.js\`. -->

Generated ${new Date().toISOString().slice(0, 10)} · ${pkgs.length} packages.

**Publish target for \`@basenative/*\` is ${registry}** (set in \`.npmrc\`), not npmjs.org.
Installing any package therefore requires a GitHub PAT with \`read:packages\` — see
[CONSUMING-FROM-GH-PACKAGES.md](CONSUMING-FROM-GH-PACKAGES.md). The npmjs column below is a
stale public mirror from before the move; it is what an external \`npm install\` resolves to.

| Package | Local | npmjs | State |
|---|---|---|---|
${rows}

## Summary

- **${publishable.length}** publishable, **${priv.length}** private (${priv.map((p) => `\`${p.name}\``).join(', ') || 'none'})
- **${behind.length}** have a stale npmjs copy that external installs resolve to
- **${absent.length}** have never appeared on npmjs
- **0** are at 1.0 on npmjs, despite ${pkgs.filter((p) => p.version.startsWith('1.')).length} being at 1.x locally
- **${redundant.length}** set \`publishConfig.registry\` to the same value \`.npmrc\` already
  supplies for the whole scope — redundant, and drifts if the scope target ever moves
`;
}

const registry = scopeRegistry();
const pkgs = readPackages();
for (const p of pkgs) p.npmjs = p.private ? null : await npmjsVersion(p.name);
const md = render(pkgs, registry);

if (process.argv.includes('--check')) {
  // Normalise away everything this repo does not control before comparing.
  //
  // The npmjs column and the counts derived from it reflect the state of a public
  // registry, so anyone publishing a version would make the committed file "stale"
  // and fail CI on an unrelated pull request. The gate exists to catch packages
  // added, removed, renamed, or version-bumped *here* — so compare the local facts
  // and treat the registry column as informational.
  const strip = (s) =>
    s
      .replace(/^Generated \d{4}-\d{2}-\d{2}.*$/m, '')
      // table rows: blank the npmjs version and the derived state cell
      .replace(/^(\| `[^`]+` \| [^|]+\|)[^|]*\|[^|]*\|$/gm, '$1 - | - |')
      // summary bullets whose numbers come from the registry
      .replace(/^- \*\*\d+\*\* have (a stale npmjs copy|never appeared).*$/gm, '')
      .replace(/^- \*\*\d+\*\* are at 1\.0 on npmjs.*$/gm, '');

  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    /* missing counts as stale */
  }
  if (strip(current) !== strip(md)) {
    console.error('docs/package-inventory.md is stale — run: node scripts/package-inventory.js');
    process.exit(1);
  }
  console.log('docs/package-inventory.md is current (registry column not gated)');
} else {
  writeFileSync(OUT, md);
  console.log(`wrote ${OUT}`);
}
