import { readdirSync, readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Corpus loader.
 *
 * The corpus is HAND-AUTHORED. This module reads and validates it; it must never
 * generate one. If the corpus is empty, the correct behaviour is to fail loudly —
 * a harness that invents its own prompts and assertions measures the model against
 * itself and returns a high, meaningless number.
 *
 * Tiers (see docs/prd-ai-native.md §W2):
 *   T1 single directive · T2 composite · T3 stateful · T4 full component
 *   T5 adversarial — prompts phrased in React/Vue idiom to measure drift directly
 */
export const TIERS = ['T1', 'T2', 'T3', 'T4', 'T5'];

/**
 * A prompt case is a JSON file:
 * {
 *   "id": "t1-interpolation-01",
 *   "tier": "T1",
 *   "prompt": "…what the model is asked for…",
 *   "context": { … },                     // context the template renders with
 *   "assertions": [                        // hand-authored; see assertions.js
 *     { "type": "renders_contains", "value": "<p>Ada</p>" }
 *   ]
 * }
 */
const REQUIRED = ['id', 'tier', 'prompt', 'assertions'];

export function loadCase(path) {
  const raw = JSON.parse(readFileSync(path, 'utf8'));
  const missing = REQUIRED.filter((k) => raw[k] === undefined);
  if (missing.length) {
    throw new Error(`${path}: missing required field(s): ${missing.join(', ')}`);
  }
  if (!TIERS.includes(raw.tier)) {
    throw new Error(`${path}: tier "${raw.tier}" is not one of ${TIERS.join(', ')}`);
  }
  if (!Array.isArray(raw.assertions) || raw.assertions.length === 0) {
    throw new Error(
      `${path}: at least one assertion is required. Assertions are hand-authored — ` +
        `do not generate them.`
    );
  }
  return raw;
}

/** Load every case under `dir`, sorted by id. Throws if the corpus is empty. */
export function loadCorpus(dir) {
  if (!existsSync(dir)) {
    throw new Error(
      `Corpus directory not found: ${dir}\n` +
        `The corpus is hand-authored and is not generated by this harness.`
    );
  }
  const files = readdirSync(dir).filter((f) => f.endsWith('.json'));
  if (files.length === 0) {
    throw new Error(
      `No prompt cases in ${dir}.\n` +
        `The corpus must be written by hand — see packages/evals/prompts/README.md.\n` +
        `Refusing to proceed: an agent-authored corpus measures the model against ` +
        `itself and produces a high, meaningless score.`
    );
  }
  const cases = files.map((f) => loadCase(join(dir, f)));
  const seen = new Set();
  for (const c of cases) {
    if (seen.has(c.id)) throw new Error(`Duplicate case id: ${c.id}`);
    seen.add(c.id);
  }
  return cases.sort((a, b) => a.id.localeCompare(b.id));
}

/** Count of cases per tier, for reporting coverage against the PRD's targets. */
export function tierCoverage(cases) {
  const counts = Object.fromEntries(TIERS.map((t) => [t, 0]));
  for (const c of cases) counts[c.tier]++;
  return counts;
}
