import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { validateTemplate } from '@basenative/validate';
import {
  loadCorpus, tierCoverage,
  scoreTemplate, summarise, computeDeltas, buildPrompt,
  resolveCredentials, extractTemplate, toMarkdown, runSuite,
} from './index.js';

/** A deliberately simple renderer, so scoring is tested without the SSR stack. */
const fakeRender = (template, ctx) =>
  template.replace(/\{\{\s*([\w.]+)\s*\}\}/g, (_, path) =>
    String(path.split('.').reduce((o, k) => (o == null ? undefined : o[k]), ctx) ?? '')
  );

const tmpCorpus = (cases) => {
  const dir = mkdtempSync(join(tmpdir(), 'bn-corpus-'));
  cases.forEach((c, i) => writeFileSync(join(dir, `case-${i}.json`), JSON.stringify(c)));
  return dir;
};

const CASE = {
  id: 't1-a', tier: 'T1', prompt: 'Show the name',
  context: { user: { name: 'Ada' } },
  assertions: [{ type: 'renders_contains', value: 'Ada' }],
};

describe('corpus loading — the hand-authored boundary', () => {
  it('loads and sorts valid cases', () => {
    const dir = tmpCorpus([{ ...CASE, id: 'b' }, { ...CASE, id: 'a' }]);
    assert.deepEqual(loadCorpus(dir).map((c) => c.id), ['a', 'b']);
  });

  // The harness must fail loudly rather than fall back to anything generated.
  it('refuses an empty corpus with an explanation', () => {
    const dir = mkdtempSync(join(tmpdir(), 'bn-empty-'));
    assert.throws(() => loadCorpus(dir), /must be written by hand/);
  });

  it('refuses a missing corpus directory', () => {
    assert.throws(() => loadCorpus('/nonexistent/corpus'), /not generated by this harness/);
  });

  it('rejects a case with no assertions', () => {
    const dir = tmpCorpus([{ ...CASE, assertions: [] }]);
    assert.throws(() => loadCorpus(dir), /at least one assertion/);
  });

  it('rejects missing required fields and unknown tiers', () => {
    const d1 = tmpCorpus([{ id: 'x', tier: 'T1' }]);
    assert.throws(() => loadCorpus(d1), /missing required field/);
    const d2 = tmpCorpus([{ ...CASE, tier: 'T9' }]);
    assert.throws(() => loadCorpus(d2), /is not one of/);
  });

  it('rejects duplicate ids', () => {
    const dir = tmpCorpus([CASE, { ...CASE }]);
    assert.throws(() => loadCorpus(dir), /Duplicate case id/);
  });

  it('reports tier coverage', () => {
    const c = tierCoverage([{ tier: 'T1' }, { tier: 'T1' }, { tier: 'T5' }]);
    assert.equal(c.T1, 2);
    assert.equal(c.T5, 1);
    assert.equal(c.T3, 0);
  });
});

describe('scoring pipeline', () => {
  it('passes a correct template', () => {
    const r = scoreTemplate({
      template: '<template @if="user"><p>{{ user.name }}</p></template>',
      testCase: CASE, validate: validateTemplate, render: fakeRender,
    });
    assert.equal(r.passed, true);
    assert.equal(r.parses, true);
    assert.equal(r.renders, true);
  });

  // A template that does not parse cannot be meaningfully rendered, so the
  // pipeline must short-circuit rather than report a misleading render failure.
  it('short-circuits at validate for drifted syntax', () => {
    const r = scoreTemplate({
      template: '<div v-if="user">{{ user.name }}</div>',
      testCase: CASE, validate: validateTemplate, render: fakeRender,
    });
    assert.equal(r.passed, false);
    assert.equal(r.failedAt, 'validate');
    assert.equal(r.renders, false);
    assert.ok(r.diagnostics.some((d) => d.code === 'BN_E_FOREIGN_DIRECTIVE'));
  });

  it('fails at assertions when it parses and renders but does the wrong thing', () => {
    const r = scoreTemplate({
      template: '<p>{{ user.email }}</p>',
      testCase: CASE, validate: validateTemplate, render: fakeRender,
    });
    assert.equal(r.parses, true);
    assert.equal(r.renders, true);
    assert.equal(r.failedAt, 'assertions');
  });

  it('reports an unknown assertion type as a failure rather than passing it', () => {
    const r = scoreTemplate({
      template: '<p>{{ user.name }}</p>',
      testCase: { ...CASE, assertions: [{ type: 'no_such_type', value: 'x' }] },
      validate: validateTemplate, render: fakeRender,
    });
    assert.equal(r.passed, false);
    assert.match(r.assertions[0].detail, /unknown assertion type/);
  });

  it('supports every documented assertion type', () => {
    const t = '<p>{{ user.name }}</p><p>{{ user.name }}</p>';
    const run = (a) =>
      scoreTemplate({ template: t, testCase: { ...CASE, assertions: [a] }, validate: validateTemplate, render: fakeRender })
        .assertions[0].pass;
    assert.equal(run({ type: 'renders_contains', value: 'Ada' }), true);
    assert.equal(run({ type: 'renders_excludes', value: 'Bob' }), true);
    assert.equal(run({ type: 'renders_matches', value: '<p>A[a-z]+</p>' }), true);
    assert.equal(run({ type: 'renders_count', value: 'Ada', count: 2 }), true);
    assert.equal(run({ type: 'renders_equals', value: '<p>Ada</p><p>Ada</p>' }), true);
    // whitespace is collapsed, but tag boundaries are not invented
    assert.equal(run({ type: 'renders_equals', value: '<p>Ada</p> <p>Ada</p>' }), false);
    assert.equal(run({ type: 'uses_directive', value: '@if' }), false);
  });
});

describe('prompt construction', () => {
  // If the two conditions differed by more than the tool sentence, the measured
  // delta would confound "has tools" with "was told more about the language".
  it('differs between MCP conditions only by the tools sentence', () => {
    const off = buildPrompt(CASE, { withMcp: false });
    const on = buildPrompt(CASE, { withMcp: true });
    assert.ok(on.includes('validate_template'));
    assert.ok(!off.includes('validate_template'));
    assert.equal(on.replace(/\n\nYou have BaseNative MCP tools[^]*?before answering\./, ''), off);
  });

  it('includes the context the template will be rendered with', () => {
    assert.match(buildPrompt(CASE, { withMcp: false }), /"name": "Ada"/);
  });
});

describe('summary and deltas', () => {
  const results = [
    { id: 'a', tier: 'T1', passed: true, diagnostics: [] },
    { id: 'b', tier: 'T5', passed: false, failedAt: 'validate', diagnostics: [{ code: 'BN_E_FOREIGN_DIRECTIVE' }] },
    { id: 'c', tier: 'T5', passed: false, failedAt: 'assertions', diagnostics: [] },
  ];

  it('computes pass rate, tier breakdown, stages and drift rate', () => {
    const s = summarise(results);
    assert.equal(s.total, 3);
    assert.equal(s.passed, 1);
    assert.ok(Math.abs(s.passRate - 1 / 3) < 1e-9);
    assert.equal(s.byTier.T5.total, 2);
    assert.equal(s.byStage.validate, 1);
    assert.equal(s.driftCount, 1);
  });

  it('computes MCP lift per model', () => {
    const d = computeDeltas([
      { model: 'm', withMcp: false, summary: { passRate: 0.4, driftRate: 0.3 } },
      { model: 'm', withMcp: true, summary: { passRate: 0.9, driftRate: 0.05 } },
    ]);
    assert.equal(d.length, 1);
    assert.ok(Math.abs(d[0].lift - 0.5) < 1e-9);
  });

  it('ignores a model that only ran one condition', () => {
    assert.deepEqual(computeDeltas([{ model: 'm', withMcp: false, summary: { passRate: 1, driftRate: 0 } }]), []);
  });
});

describe('providers', () => {
  it('names every provider whose key is missing rather than narrowing the run', () => {
    assert.throws(
      () => resolveCredentials([{ provider: 'anthropic' }, { provider: 'openai' }], {}),
      /ANTHROPIC_API_KEY[^]*OPENAI_API_KEY/
    );
  });

  it('refuses a partial leaderboard even when one key is present', () => {
    assert.throws(
      () => resolveCredentials([{ provider: 'anthropic' }, { provider: 'google' }], { ANTHROPIC_API_KEY: 'k' }),
      /refuses to run a partial leaderboard/
    );
  });

  it('rejects an unknown provider', () => {
    assert.throws(() => resolveCredentials([{ provider: 'nope' }], {}), /Unknown provider/);
  });

  it('strips markdown fences from model output', () => {
    assert.equal(extractTemplate('```html\n<p>x</p>\n```'), '<p>x</p>');
    assert.equal(extractTemplate('<p>x</p>'), '<p>x</p>');
  });
});

describe('end to end', () => {
  it('runs a suite with an injected generator and produces a report', async () => {
    const cases = [
      CASE,
      { id: 't5-a', tier: 'T5', prompt: 'conditionally render the greeting',
        context: { ok: true }, assertions: [{ type: 'renders_contains', value: 'hi' }] },
    ];
    // The stub drifts to Vue on the adversarial prompt, exactly as a real model might.
    const generate = async (prompt) =>
      prompt.includes('conditionally render')
        ? '<div v-if="ok">hi</div>'
        : '<template @if="user"><p>{{ user.name }}</p></template>';

    const suite = await runSuite({ cases, models: [{ id: 'stub' }], generate, render: fakeRender, conditions: [false] });
    assert.equal(suite.runs.length, 1);
    assert.equal(suite.runs[0].summary.passed, 1);
    assert.equal(suite.runs[0].summary.driftCount, 1);
    assert.equal(suite.coverage.T1, 1);

    const md = toMarkdown(suite);
    assert.match(md, /# BaseNative eval results/);
    assert.match(md, /Corpus coverage/);
    assert.match(md, /50\.0%/);
  });
});
